package org.example.model;

public class OportunidadeIA {

    private String tag;
    private String descricao;

    public OportunidadeIA(String tag, String descricao) {
        this.tag = tag;
        this.descricao = descricao;
    }

    public String getTag() {
        return tag;
    }

    public String getDescricao() {
        return descricao;
    }
}